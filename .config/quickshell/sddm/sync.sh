#!/bin/sh
# Copies the current matugen palette and wallpaper into the SDDM theme's state dir (no sudo needed
# once install.sh has made it writable). Run by matugen after every palette change.
STATE="${XDG_STATE_HOME:-$HOME/.local/state}/quickshell"
OUT="${THEME_DIR:-/usr/share/sddm/themes/quickshell}/state"
[ -w "$OUT" ] || { echo "sync.sh: $OUT is not writable (run install.sh)" >&2; exit 1; }

python3 - "$STATE/colors.json" "$OUT/Colors.qml" <<'PY'
import json, sys
src, dst = sys.argv[1:]
c = json.load(open(src))
lines = ["pragma Singleton", "import QtQuick", "", "// generated by sync.sh from the shell's colors.json", "QtObject {"]
lines += [f'    readonly property color {k}: "{v}"' for k, v in sorted(c.items())]
lines.append("}")
open(dst + ".tmp", "w").write("\n".join(lines) + "\n")
PY
mv "$OUT/Colors.qml.tmp" "$OUT/Colors.qml"

wall="$(cat "$STATE/current-wallpaper" 2>/dev/null)"
if [ -f "$wall" ]; then
    magick "$wall" -resize '1920x1080^' -quality 85 "$OUT/bg.jpg.tmp.jpg" && mv "$OUT/bg.jpg.tmp.jpg" "$OUT/bg.jpg"
fi
chmod a+r "$OUT"/*
