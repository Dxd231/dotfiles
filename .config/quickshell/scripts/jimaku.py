#!/usr/bin/env python3
"""Jimaku (jimaku.cc) subtitles for mpv and the shell: finds the Japanese subtitle for a video, cleans it
(drops Chinese lines, karaoke and drawings, converts .ass/.vtt to .srt) and saves it next to the video
as <video name>.ja.srt. Input comes in on stdin as JSON, never on argv; the result is printed as JSON.

State: <state>/quickshell/immersion/jimaku.json
  { files: {"<video path>": {state, entry, ep, saved, chosen, converted, cleaned, blocked, candidates, error, at}},
    blacklist: ["group or word", ..], pins: {"<show key>": entryId} }
  state is searching | saved | none | nokey | error
Hints:  <state>/quickshell/immersion/jimaku-hints.json  (written by the shell)
  {"<video path>": {anilistId, ep, key}}
Key:    <state>/quickshell/jimaku-auth.json  {key}  (mode 600, outside the dotfiles repo)

  jimaku.py fetch    stdin {path, force?}
  jimaku.py pick     stdin {path, url, name}          save that candidate instead
  jimaku.py search   stdin {q}                        -> prints a list of Jimaku entries
  jimaku.py pin      stdin {path, id}                 use this Jimaku entry for the show; then fetch
  jimaku.py block    stdin {name} / unblock           edit the author blacklist
  jimaku.py key      stdin {key}                      check the key, then keep it
  jimaku.py logout
"""
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import time
import urllib.error
import urllib.parse
import urllib.request
import zipfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import anilist  # noqa: E402

API = os.environ.get("JIMAKU_API") or "https://jimaku.cc/api"  # the env var is for tests
UA = "quickshell-jimaku/1.0"
STATE = anilist.STATE
DIR = anilist.DIR
FILE = os.path.join(DIR, "jimaku.json")
HINTS = os.path.join(DIR, "jimaku-hints.json")
AUTH = os.path.join(STATE, "jimaku-auth.json")
KEEP = 50
SUB_EXT = (".srt", ".vtt", ".ass", ".ssa")
ARCHIVE_EXT = (".zip", ".rar", ".7z")
MAX_BYTES = 40 * 1024 * 1024

# machine / AI output; named groups are the user's to add ("Block author" in the panel)
SEED_BLOCK = ["whisper", "machine", "mtl", "auto-generated", "autogenerated", "ai-generated", "ai generated",
              "ai sub", "chatgpt", "gpt"]
ZH_TAG = re.compile(r"(?<![a-z])(chs|cht|sc|tc|gb|big5|zh|chi|zho)(?![a-z])|简|繁|中文|chinese", re.I)
BI_TAG = re.compile(r"(?<![a-z])(chs|cht|sc|tc|zh)[&_+\-.\s]*(jp|jpn|ja)(?![a-z])|(?<![a-z])(jp|jpn|ja)[&_+\-.\s]*"
                    r"(chs|cht|sc|tc|zh)(?![a-z])|简日|繁日|日简|日繁|中日|日中|双语|雙語|bilingual", re.I)
KANA = re.compile(r"[\u3040-\u30ff\uff66-\uff9f]")
HAN = re.compile(r"[\u3400-\u9fff]")
# characters Japanese never uses (simplified forms and a few traditional ones)
ZH_ONLY = set("们这么对个为让说吗呢还时过样开关东问应该没爱见们麼個為讓說嗎樣關應")
SKIP_STYLE = re.compile(r"(?<![a-z])(op|ed|song|kara|karaoke|insert)(?![a-z])", re.I)

# file-name reading, the same rules as anime_scan.py (which can't be imported: it scans on import)
TAGS = re.compile(r"\[[^\]]*\]|【[^】]*】")
CODEC_PARENS = re.compile(r"\([^)]*(?:\d{3,4}p|BD|BDRip|AV1|HEVC|x26[45]|Opus|FLAC|AAC)[^)]*\)", re.I)


def clean(s):
    s = CODEC_PARENS.sub(" ", TAGS.sub(" ", s))
    return re.sub(r"\s+", " ", s.replace("_", " ")).strip()


def episode_of(raw, text):
    m = re.search(r"\[(\d{1,3})(?:v\d)?\]", raw)
    if m:
        return int(m.group(1))
    for pat in (r"\sS\d{1,2}\s*-\s*(\d{1,3})(?:v\d)?(?=\s|$)", r"\s[-–]\s*(\d{1,3})(?:v\d)?(?=\s|$|\W)",
                r"\bE(?:P|pisode)?\s*\.?(\d{1,3})\b"):
        m = re.search(pat, text, re.I)
        if m:
            return int(m.group(1))
    return 0


class Fail(Exception):
    def __init__(self, state, msg=""):
        Exception.__init__(self, msg)
        self.state = state
        self.msg = msg


# ---- state ----
def status():
    s = anilist.load(FILE, {})
    if not isinstance(s, dict):
        s = {}
    for k, d in (("files", {}), ("pins", {})):
        if not isinstance(s.get(k), dict):
            s[k] = d
    if not isinstance(s.get("blacklist"), list):
        s["blacklist"] = []
    return s


def put(path, **fields):
    """Replace the record of one video and keep the file small."""
    s = status()
    rec = {"at": int(time.time())}
    rec.update(fields)
    s["files"][path] = rec
    if len(s["files"]) > KEEP:
        for k in sorted(s["files"], key=lambda x: s["files"][x].get("at", 0))[:len(s["files"]) - KEEP]:
            del s["files"][k]
    anilist.save(FILE, s)
    return rec


def api_key():
    k = anilist.load(AUTH, {}).get("key")
    return k.strip() if isinstance(k, str) else ""


# ---- http ----
def http(url, key=None, limit=MAX_BYTES):
    headers = {"User-Agent": UA, "Accept": "*/*"}
    if key and urllib.parse.urlparse(url).hostname == "jimaku.cc":
        headers["Authorization"] = key
    try:
        with urllib.request.urlopen(urllib.request.Request(url, headers=headers), timeout=25) as r:
            data = r.read(limit + 1)
    except urllib.error.HTTPError as e:
        if e.code == 401:
            raise Fail("nokey", "Jimaku rejected the key")
        if e.code == 429:
            raise Fail("error", "Jimaku rate limit, try again in a moment")
        if e.code == 404:
            return None
        raise Fail("error", "Jimaku answered %d" % e.code)
    except (urllib.error.URLError, OSError):
        raise Fail("error", "Can't reach jimaku.cc")
    if len(data) > limit:
        raise Fail("error", "File too large")
    return data


def jget(path, key, **params):
    q = urllib.parse.urlencode({k: v for k, v in params.items() if v not in (None, "")})
    data = http("%s%s%s" % (API, path, "?" + q if q else ""), key)
    if data is None:
        return None
    try:
        return json.loads(data)
    except ValueError:
        raise Fail("error", "Unexpected answer from Jimaku")


# ---- what is playing ----
def stem_of(path):
    return os.path.splitext(os.path.basename(path))[0]


def ep_of(name):
    """Episode number in a file name, 0 when there isn't one."""
    stem = os.path.splitext(name)[0] if name.lower().endswith(SUB_EXT + ARCHIVE_EXT) else name
    text = clean(stem)
    m = re.search(r"\bS\d{1,2}\s*E(\d{1,3})(?:v\d)?\b", text, re.I)
    return int(m.group(1)) if m else episode_of(stem, text)


def guess(path):
    """-> (show name, episode) read from the file and folder names."""
    stem = stem_of(path)
    text = clean(stem)
    ep = ep_of(stem)
    name = re.sub(r"\bS\d{1,2}\s*E\d{1,3}(?:v\d)?\b.*$", "", text, flags=re.I)
    name = re.sub(r"\s[-–]\s*\d{1,3}(?:v\d)?(?=\s|$).*$", "", name).strip(" -–.")
    folders = [clean(p) for p in os.path.dirname(path).split("/") if p]
    if len(name) < 3 and folders:
        name = re.sub(r"(?:^|[\s\-–]+)(?:S|Season\s*)\d{1,2}$", "", folders[-1], flags=re.I).strip() or folders[-1]
    return name, ep


def entry_of(e):
    return {"id": e.get("id"), "name": e.get("name") or "", "japanese": e.get("japanese_name") or "",
            "english": e.get("english_name") or "", "anilistId": e.get("anilist_id")}


def find_entry(path, hint, key, pins):
    name, ep = guess(path)
    ep = hint.get("ep") or ep
    pin = pins.get(hint.get("key") or "name:" + name.lower())
    if pin:
        e = jget("/entries/%d" % pin, key)
        if e:
            return entry_of(e), ep
    aid = hint.get("anilistId")
    if not aid and name:
        try:
            hits = ((anilist.gql(anilist.SEARCH, {"q": name}) or {}).get("Page") or {}).get("media") or []
        except anilist.RateLimited:
            hits = []
        aid = hits[0]["id"] if hits else None
    if aid:
        found = jget("/entries/search", key, anilist_id=aid)
        if found:
            return entry_of(found[0]), ep
    if name:
        found = jget("/entries/search", key, query=name, anime="true")
        if found:
            return entry_of(found[0]), ep
    raise Fail("none", "Not on Jimaku")


# ---- choosing among the files of an entry ----
def groups_of(name):
    return [(a or b).strip().lower() for a, b in re.findall(r"\[([^\]]+)\]|\(([^)]+)\)", name)]


def blocked_by(name, user):
    low = name.lower()
    tags = groups_of(name)
    for w in SEED_BLOCK:
        if w in low:
            return "machine-made"
    for w in user:
        w = str(w).strip().lower()
        if w and (w in tags or (len(w) >= 4 and w in low)):
            return "blocked: " + w
    return None


def classify(name):
    if BI_TAG.search(name):
        return "bi"
    if ZH_TAG.search(name):
        return "zh"
    return "ja"


def rank(c, ep, video_stem):
    n = c["name"].lower()
    cep = ep_of(c["name"])
    ext = os.path.splitext(n)[1]
    order = {".srt": 0, ".vtt": 1, ".ass": 2, ".ssa": 3}.get(ext, 4)
    ep_miss = 0 if (not ep or cep == ep) else (1 if cep == 0 else 5)
    words = {w for w in re.split(r"[^a-z0-9]+", video_stem.lower()) if len(w) >= 2}
    overlap = sum(1 for w in re.split(r"[^a-z0-9]+", n) if w in words)
    return ((100 if c["cls"] == "bi" else 0) + ep_miss * 10 + order, -overlap, -c.get("size", 0))


def candidates_of(files, ep, user, video_stem):
    out = []
    for f in files:
        name = f.get("name") or ""
        ext = os.path.splitext(name.lower())[1]
        if ext not in SUB_EXT + ARCHIVE_EXT:
            continue
        c = {"name": name, "url": f.get("url") or "", "size": f.get("size") or 0, "cls": classify(name)}
        c["blocked"] = blocked_by(name, user) or ("chinese" if c["cls"] == "zh" else None)
        out.append(c)
    out.sort(key=lambda c: rank(c, ep, video_stem))
    return out


# ---- reading subtitles ----
def decode(data):
    if data[:2] in (b"\xff\xfe", b"\xfe\xff"):
        return data.decode("utf-16", "replace")
    for enc in ("utf-8-sig", "cp932", "gb18030"):
        try:
            return data.decode(enc)
        except UnicodeDecodeError:
            pass
    return data.decode("utf-8", "replace")


def secs(t):
    m = re.match(r"\s*(?:(\d+):)?(\d+):(\d+)[.,](\d+)", t)
    if not m:
        return None
    h, mi, s, f = m.groups()
    return int(h or 0) * 3600 + int(mi) * 60 + int(s) + int(f.ljust(3, "0")[:3]) / 1000.0


def parse_srt(text):
    cues = []
    for block in re.split(r"\n\s*\n", text.replace("\r\n", "\n").replace("\r", "\n")):
        lines = [l for l in block.split("\n")]
        for i, l in enumerate(lines):
            if "-->" in l:
                a, b = l.split("-->", 1)
                s, e = secs(a), secs(b.split()[0] if b.split() else b)
                body = [x for x in lines[i + 1:] if x.strip() != ""]
                if s is not None and e is not None and body:
                    cues.append({"start": s, "end": e, "lines": body, "style": ""})
                break
    return cues


def parse_ass(text):
    cues = []
    cols = None
    in_events = False
    for raw in text.replace("\r\n", "\n").replace("\r", "\n").split("\n"):
        line = raw.strip()
        if line.startswith("["):
            in_events = line.lower() == "[events]"
            continue
        if not in_events:
            continue
        if line.lower().startswith("format:"):
            cols = [c.strip().lower() for c in line[7:].split(",")]
        elif line.lower().startswith("dialogue:") and cols and "text" in cols:
            parts = line[9:].lstrip().split(",", len(cols) - 1)
            if len(parts) < len(cols):
                continue
            row = dict(zip(cols, parts))
            body = row["text"]
            style = row.get("style", "").strip().lstrip("*")
            if re.search(r"\\p[1-9]", body) or re.search(r"\\k[fo]?\d", body) or SKIP_STYLE.search(style):
                continue
            body = re.sub(r"\{[^}]*\}", "", body).replace("\\h", " ")
            body = [x.strip() for x in re.split(r"\\[Nn]", body)]
            body = [x for x in body if x]
            s, e = secs(row.get("start", "")), secs(row.get("end", ""))
            if body and s is not None and e is not None:
                cues.append({"start": s, "end": e, "lines": body, "style": style})
    return cues


def parse(name, data):
    text = decode(data)
    ext = os.path.splitext(name.lower())[1]
    return parse_ass(text) if ext in (".ass", ".ssa") else parse_srt(text)


def kana_share(cues):
    return sum(1 for c in cues if KANA.search(" ".join(c["lines"]))) / float(len(cues) or 1)


def zh_marked(line):
    return not KANA.search(line) and any(ch in ZH_ONLY for ch in line)


def is_bilingual(cues):
    n = sum(1 for c in cues if any(zh_marked(l) for l in c["lines"]) and any(KANA.search(l) for l in c["lines"]))
    return n >= max(3, 0.05 * len(cues))


def clean_chinese(cues):
    """Drop the Chinese half of a Chinese + Japanese file: whole styles that are Chinese, then the lines
    that are Chinese inside events that hold both."""
    styles = {}
    for c in cues:
        st = styles.setdefault(c["style"], [0, 0])
        st[0] += 1
        if any(zh_marked(l) for l in c["lines"]):
            st[1] += 1
    zh_styles = {s for s, (n, z) in styles.items() if s and z >= 0.3 * n and not any(
        KANA.search(" ".join(c["lines"])) for c in cues if c["style"] == s)}
    out = []
    for c in cues:
        if c["style"] in zh_styles:
            continue
        lines = c["lines"]
        if len(lines) > 1 and any(KANA.search(l) for l in lines):
            # a line without kana beside one with kana is the translation; drop it
            lines = [l for l in lines if KANA.search(l) or not HAN.search(l)] or lines
        out.append({"start": c["start"], "end": c["end"], "lines": lines, "style": c["style"]})
    return out


def stamp(t):
    ms = int(round(t * 1000))
    return "%02d:%02d:%02d,%03d" % (ms // 3600000, ms // 60000 % 60, ms // 1000 % 60, ms % 1000)


def to_srt(cues):
    merged = {}
    for c in cues:
        k = (round(c["start"], 2), round(c["end"], 2))
        lines = merged.setdefault(k, [])
        for l in c["lines"]:
            if l not in lines:
                lines.append(l)
    out = []
    for i, ((s, e), lines) in enumerate(sorted(merged.items()), 1):
        out.append("%d\n%s --> %s\n%s\n" % (i, stamp(s), stamp(e), "\n".join(lines)))
    return "\n".join(out)


# ---- archives ----
def unpack(name, data):
    """-> [(member name, bytes)] of the subtitle files inside an archive."""
    tmp = tempfile.mkdtemp(prefix="jimaku-")
    try:
        arc = os.path.join(tmp, "a" + os.path.splitext(name.lower())[1])
        with open(arc, "wb") as f:
            f.write(data)
        out_dir = os.path.join(tmp, "out")
        os.makedirs(out_dir)
        if arc.endswith(".zip"):
            try:
                with zipfile.ZipFile(arc) as z:
                    z.extractall(out_dir)
            except zipfile.BadZipFile:
                raise Fail("error", "Broken archive")
        else:
            subprocess.run(["7z", "x", "-y", "-o" + out_dir, arc], capture_output=True, timeout=60)
        found = []
        root = os.path.realpath(out_dir)
        for base, _, names in os.walk(out_dir):
            for n in names:
                p = os.path.join(base, n)
                if os.path.islink(p) or not os.path.realpath(p).startswith(root + os.sep):
                    continue
                if n.lower().endswith(SUB_EXT) and os.path.getsize(p) <= MAX_BYTES:
                    with open(p, "rb") as f:
                        found.append((n, f.read()))
        return found
    except (OSError, subprocess.SubprocessError):
        raise Fail("error", "Couldn't open the archive")
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


# ---- one candidate -> subtitle text ----
def process(c, ep, key, strict):
    """Download a candidate and turn it into SRT text. -> (srt, flags). Raises Fail when it is no good."""
    data = http(c["url"], key)
    if not data:
        raise Fail("error", "Download failed")
    name = c["name"]
    if name.lower().endswith(ARCHIVE_EXT):
        members = [(n, d) for n, d in unpack(name, data) if classify(n) != "zh" or not strict]
        if ep:
            same = [m for m in members if ep_of(m[0]) == ep]
            members = same or ([] if len(members) > 1 else members)
        if not members:
            raise Fail("none", "No matching episode in the archive")
        members.sort(key=lambda m: (classify(m[0]) == "bi", {".srt": 0, ".vtt": 1, ".ass": 2, ".ssa": 3}.get(
            os.path.splitext(m[0].lower())[1], 4)))
        name, data = members[0]
    cues = parse(name, data)
    if not cues:
        raise Fail("none", "Empty subtitle")
    if strict and kana_share(cues) < 0.05:
        raise Fail("none", "Not Japanese")
    flags = {"converted": not name.lower().endswith(".srt"), "cleaned": False}
    if classify(name) == "bi" or is_bilingual(cues):
        before = len(cues)
        cues = clean_chinese(cues)
        flags["cleaned"] = True
        if not cues or len(cues) < 0.5 * before:
            raise Fail("none", "Nothing left after cleaning")
    return to_srt(cues), flags


def save_to(path, srt):
    dest = os.path.join(os.path.dirname(path), stem_of(path) + ".ja.srt")
    fd, tmp = tempfile.mkstemp(dir=os.path.dirname(path), prefix=".jimaku-")
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(srt)
    os.chmod(tmp, 0o644)
    os.replace(tmp, dest)
    return dest


def existing(path):
    d = os.path.dirname(path)
    pre = stem_of(path) + ".ja."
    try:
        return next((os.path.join(d, n) for n in sorted(os.listdir(d)) if n.startswith(pre) and n.lower().endswith(SUB_EXT)), "")
    except OSError:
        return ""


# ---- commands ----
def list_files(entry, ep, key):
    files = jget("/entries/%d/files" % entry["id"], key, episode=ep or None)
    if not files and ep:
        files = [f for f in (jget("/entries/%d/files" % entry["id"], key) or [])
                 if ep_of(f.get("name") or "") in (ep, 0)]
    return files or []


def do_fetch(a):
    path = a.get("path") or ""
    if not path.startswith("/") or not os.path.isfile(path):
        return {"ok": False, "state": "error", "error": "Not a local file"}
    if not a.get("force") and existing(path):
        rec = status()["files"].get(path) or {}
        if rec.get("state") != "saved":
            put(path, state="saved", saved=existing(path), chosen=os.path.basename(existing(path)), ep=rec.get("ep", 0))
        return {"ok": True, "state": "saved", "saved": existing(path), "kept": True}
    key = api_key()
    if not key:
        put(path, state="nokey")
        return {"ok": False, "state": "nokey"}
    put(path, state="searching")
    s = status()
    hint = (anilist.load(HINTS, {}) or {}).get(path) or {}
    ent, ep = None, 0
    try:
        ent, ep = find_entry(path, hint, key, s["pins"])
        cands = candidates_of(list_files(ent, ep, key), ep, s["blacklist"], stem_of(path))
        usable = [c for c in cands if not c["blocked"]]
        nblocked = len(cands) - len(usable)
        for c in usable[:5]:
            try:
                srt, flags = process(c, ep, key, True)
            except Fail as e:
                if e.state == "none":
                    c["blocked"] = e.msg
                    continue
                raise
            dest = save_to(path, srt)
            put(path, state="saved", entry=ent, ep=ep, saved=dest, chosen=c["name"], candidates=cands, nblocked=nblocked, **flags)
            return {"ok": True, "state": "saved", "saved": dest}
        put(path, state="none", entry=ent, ep=ep, candidates=cands, nblocked=len(cands) - len([c for c in cands if not c["blocked"]]))
        return {"ok": False, "state": "none"}
    except Fail as e:
        put(path, state=e.state, entry=ent, ep=ep, error=e.msg)
        return {"ok": False, "state": e.state, "error": e.msg}


def do_pick(a):
    path = a.get("path") or ""
    key = api_key()
    rec = status()["files"].get(path) or {}
    c = {"name": a.get("name") or "", "url": a.get("url") or ""}
    try:
        srt, flags = process(c, rec.get("ep") or 0, key, False)
    except Fail as e:
        return {"ok": False, "state": e.state, "error": e.msg}
    dest = save_to(path, srt)
    rec.update(state="saved", saved=dest, chosen=c["name"], error="", at=int(time.time()), **flags)
    s = status()
    s["files"][path] = rec
    anilist.save(FILE, s)
    return {"ok": True, "state": "saved", "saved": dest}


def do_search(a):
    try:
        found = jget("/entries/search", api_key(), query=a.get("q") or "", anime="true") or []
    except Fail:
        found = []
    return [entry_of(e) for e in found[:12]]


def do_pin(a):
    path = a.get("path") or ""
    hint = (anilist.load(HINTS, {}) or {}).get(path) or {}
    name, _ = guess(path)
    s = status()
    s["pins"][hint.get("key") or "name:" + name.lower()] = int(a["id"])
    anilist.save(FILE, s)
    return do_fetch({"path": path, "force": True})


def do_block(a, on):
    w = str(a.get("name") or "").strip().lower()
    s = status()
    if on and w and w not in s["blacklist"]:
        s["blacklist"].append(w)
    elif not on:
        s["blacklist"] = [x for x in s["blacklist"] if x != w]
    anilist.save(FILE, s)
    return {"ok": True}


def do_key(a):
    k = str(a.get("key") or "").strip()
    try:
        jget("/entries/search", k, query="a", anime="true")
    except Fail as e:
        return {"ok": False, "error": e.msg}
    anilist.save(AUTH, {"key": k}, 0o600)
    return {"ok": True}


def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    if cmd == "logout":
        try:
            os.remove(AUTH)
        except OSError:
            pass
        print(json.dumps({"ok": True}))
        return
    try:
        arg = json.loads(sys.stdin.read() or "{}") or {}
    except ValueError:
        return
    try:
        if cmd == "fetch":
            out = do_fetch(arg)
        elif cmd == "pick":
            out = do_pick(arg)
        elif cmd == "search":
            out = do_search(arg)
        elif cmd == "pin":
            out = do_pin(arg)
        elif cmd in ("block", "unblock"):
            out = do_block(arg, cmd == "block")
        elif cmd == "key":
            out = do_key(arg)
        else:
            return
    except Fail as e:
        out = {"ok": False, "state": e.state, "error": e.msg}
    print(json.dumps(out, ensure_ascii=False))


if __name__ == "__main__":
    main()
